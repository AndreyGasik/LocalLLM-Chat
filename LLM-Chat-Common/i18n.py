_CURRENT_LANG = "ru"

def get_lang() -> str:
    return _CURRENT_LANG

def set_lang(lang: str) -> None:
    global _CURRENT_LANG
    if lang in ("ru", "en"):
        _CURRENT_LANG = lang

def _t(_tr_id: str, **kwargs) -> str:
    entry = _TR.get(_tr_id, {})
    s = entry.get(get_lang(), entry.get("ru", _tr_id))
    return s.format(**kwargs) if kwargs else s

# Alias for convenience
t = _t
